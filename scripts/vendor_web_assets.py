#!/usr/bin/env python3
"""Refresh the self-hosted Chart.js and web fonts in static/vendor/.

The dashboard serves these locally instead of from jsDelivr and Google Fonts, so
pages load offline, no visit is disclosed to a third party, and a compromised CDN
cannot run script on pages with device controls. Versions are exact pins; bump
them here, run this script (needs npm and registry access), review the diff, and
commit static/vendor/ including UPSTREAM.json.

    python3 scripts/vendor_web_assets.py
"""
from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import tarfile
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / "static" / "vendor"

CHART_JS = "chart.js@4.5.1"
INTER = "@fontsource-variable/inter@5.3.0"
INSTRUMENT_SERIF = "@fontsource/instrument-serif@5.3.0"

# Same Unicode subsets Google Fonts served: browsers fetch only the subsets a page uses.
LATIN = ("U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,"
         "U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD")
LATIN_EXT = ("U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,"
             "U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,"
             "U+2113,U+2C60-2C7F,U+A720-A7FF")

# (destination, package, path inside the package)
FILES = [
    ("chart.umd.min.js", CHART_JS, "dist/chart.umd.min.js"),
    ("LICENSE-chart.js.md", CHART_JS, "LICENSE.md"),
    ("LICENSE-inter.txt", INTER, "LICENSE"),
    ("LICENSE-instrument-serif.txt", INSTRUMENT_SERIF, "LICENSE"),
]
for subset in ("latin", "latin-ext"):
    for style in ("normal", "italic"):
        FILES.append((f"fonts/inter-{subset}-opsz-{style}.woff2", INTER,
                      f"files/inter-{subset}-opsz-{style}.woff2"))
        FILES.append((f"fonts/instrument-serif-{subset}-400-{style}.woff2", INSTRUMENT_SERIF,
                      f"files/instrument-serif-{subset}-400-{style}.woff2"))


def font_css() -> str:
    """@font-face rules keeping the family names web.py's CSS already uses."""
    rules = ["/* Generated by scripts/vendor_web_assets.py — do not edit by hand. */"]
    for subset, ranges in (("latin-ext", LATIN_EXT), ("latin", LATIN)):
        for style in ("normal", "italic"):
            inter = f"/static/vendor/fonts/inter-{subset}-opsz-{style}.woff2"
            serif = f"/static/vendor/fonts/instrument-serif-{subset}-400-{style}.woff2"
            rules.append(
                f"@font-face{{font-family:'Inter';font-style:{style};font-display:swap;"
                f"font-weight:100 900;src:url({inter}) format('woff2-variations'),"
                f"url({inter}) format('woff2');unicode-range:{ranges};}}")
            rules.append(
                f"@font-face{{font-family:'Instrument Serif';font-style:{style};"
                f"font-display:swap;font-weight:400;src:url({serif}) format('woff2');"
                f"unicode-range:{ranges};}}")
    return "\n".join(rules) + "\n"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fetch(spec: str, workdir: Path) -> Path:
    """Download one exact npm package version and return its extracted root."""
    output = subprocess.run(["npm", "pack", "--silent", spec], cwd=workdir, check=True,
                            capture_output=True, text=True).stdout.strip().splitlines()[-1]
    target = workdir / output.removesuffix(".tgz")
    target.mkdir()
    with tarfile.open(workdir / output) as archive:
        archive.extractall(target, filter="data")
    return target / "package"


def main() -> None:
    with tempfile.TemporaryDirectory() as temp:
        workdir = Path(temp)
        packages = {spec: fetch(spec, workdir) for spec in {spec for _, spec, _ in FILES}}
        if VENDOR.exists():
            shutil.rmtree(VENDOR)
        (VENDOR / "fonts").mkdir(parents=True)
        for destination, spec, source in FILES:
            shutil.copyfile(packages[spec] / source, VENDOR / destination)
    (VENDOR / "fonts.css").write_text(font_css())
    record = {
        "purpose": "Self-hosted dashboard assets; refresh with scripts/vendor_web_assets.py",
        "packages": {
            CHART_JS: {"license": "MIT", "registry": "https://registry.npmjs.org"},
            INTER: {"license": "OFL-1.1", "registry": "https://registry.npmjs.org"},
            INSTRUMENT_SERIF: {"license": "OFL-1.1", "registry": "https://registry.npmjs.org"},
        },
        "files": {path.relative_to(VENDOR).as_posix(): sha256(path)
                  for path in sorted(VENDOR.rglob("*"))
                  if path.is_file() and path.name != "UPSTREAM.json"},
    }
    (VENDOR / "UPSTREAM.json").write_text(json.dumps(record, indent=2) + "\n")
    print(f"Vendored {len(record['files'])} files into {VENDOR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
